#!/usr/bin/env python3
"""CAIRN experiments (host-side, CPython, seeded -> reproducible).

DATA STATUS: every number produced here comes from SYNTHETIC data generated by
this script and executed on a HOST computer with the same firmware modules.
It is NOT a measurement on an ESP32 nor in the Wokwi simulator.

    python3 experiments/run_experiments.py
"""
import json
import os
import random
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "firmware"))
from chainlog import ChainLog, verify_records, canonical, to_hex, sha256  # noqa: E402
from plausibility import Plausibility  # noqa: E402

K0 = b"E" * 32
SEED = 20261116
TRIALS = 300
OUT = os.path.join(HERE, "results")
os.makedirs(OUT, exist_ok=True)


# ----------------------------------------------------------------- E1: tampering
def build_log(rnd):
    d = tempfile.mkdtemp()
    log = ChainLog(os.path.join(d, "l"), os.path.join(d, "s"), K0)
    n = rnd.randint(20, 150)
    names = ["HB", "MOTION", "GAS_ALARM", "TEMP_JUMP", "HB", "HB"]
    for i in range(n):
        log.append(1_000_000 + 2 * i, rnd.choice(names), rnd.randint(0, 4000))
    with open(log.path) as f:
        return log, f.read().splitlines()


def hide(rec):
    if rec["e"] != "HB":
        rec["e"] = "HB"
    else:
        rec["v"] = "0"


def attack(kind, lines, rnd, log):
    """Return (tampered_lines, first_affected_seq, forged_by_key_holder)."""
    n = len(lines)
    i = rnd.randint(1, n - 5)                      # never the first/last few
    if kind == "EDIT":
        r = json.loads(lines[i]); hide(r); lines[i] = json.dumps(r)
        return lines, i + 1
    if kind == "DELETE":
        del lines[i]
        return lines, i + 1
    if kind == "REORDER":
        lines[i], lines[i + 1] = lines[i + 1], lines[i]
        return lines, i + 1
    if kind == "INSERT_FAKE":
        r = json.loads(lines[i]); r["e"] = "MOTION"; r["v"] = "1"
        lines.insert(i, json.dumps(r))
        return lines, i + 1
    if kind == "TRUNCATE_TAIL":
        return lines[:-3], n - 2
    if kind == "EDIT_REHASH":                      # attacker recomputes hashes, lacks key
        recs = [json.loads(x) for x in lines]
        hide(recs[i]); prev = recs[i]["p"]
        for r in recs[i:]:
            r["p"] = prev
            r["h"] = to_hex(sha256(canonical(r["s"], r["t"], r["e"], r["v"], prev).encode()))
            prev = r["h"]
        return [json.dumps(r) for r in recs], i + 1
    raise ValueError(kind)


def key_holder_forgery(log, lines):
    """Attacker steals the CURRENT key and appends forged records (documented limit)."""
    log.append(2_000_000, "HB", "forged")
    with open(log.path) as f:
        return f.read().splitlines()


def experiment_tamper():
    rnd = random.Random(SEED)
    kinds = ["EDIT", "DELETE", "REORDER", "INSERT_FAKE", "TRUNCATE_TAIL", "EDIT_REHASH"]
    res = {}
    for kind in kinds:
        stats = {"chain_only": 0, "chain_mac": 0, "chain_mac_anchor": 0, "localised": 0}
        for _ in range(TRIALS):
            log, lines = build_log(rnd)
            anchor = (log.seq, log.head)
            t, first = attack(kind, list(lines), rnd, log)
            r1 = verify_records(t)
            r2 = verify_records(t, K0)
            r3 = verify_records(t, K0, anchor)
            stats["chain_only"] += not r1["ok"]
            stats["chain_mac"] += not r2["ok"]
            stats["chain_mac_anchor"] += not r3["ok"]
            if not r3["ok"] and r3["bad_seq"] == first:
                stats["localised"] += 1
        res[kind] = {k: round(100.0 * v / TRIALS, 1) for k, v in stats.items()}
    # documented limit: key compromise (forgery of FUTURE records)
    ok = 0
    for _ in range(TRIALS):
        log, lines = build_log(rnd)
        anchor = (log.seq, log.head)
        forged = key_holder_forgery(log, lines)
        ok += not verify_records(forged, K0, anchor)["ok"]
    res["KEY_COMPROMISE_APPEND"] = {"chain_only": 0.0, "chain_mac": 0.0,
                                    "chain_mac_anchor": round(100.0 * ok / TRIALS, 1),
                                    "localised": 0.0}
    return res


# ----------------------------------------------------------- E2: plausibility
TICK = 0.5            # seconds per simulated tick; temp/gas sampled every 4 ticks (2 s)


def normal_trace(rnd, n=1500):
    t, rows = 24.0, []
    pir_hold = 0
    for k in range(n):
        if k % 4 == 0:
            t += rnd.gauss(0, 0.05)
        pir = 0
        if pir_hold > 0:
            pir, pir_hold = 1, pir_hold - 1
        elif rnd.random() < 0.01:
            pir, pir_hold = 1, 3
        rows.append({"k": k, "temp": t, "gas": int(rnd.gauss(400, 30)), "pir": pir})
    return rows


def inject(rows, fault, at):
    n = len(rows)
    for j in range(at, n):
        r = rows[j]
        if fault == "TEMP_SPOOF":
            if at <= j < at + 40:
                r["temp"] += 9.0
        elif fault == "GAS_SPIKE_1200":
            if at <= j < at + 40:
                r["gas"] = 1200 + rnd_small(j)
        elif fault == "GAS_ALARM_2400":
            if at <= j < at + 40:
                r["gas"] = 2400
        elif fault == "GAS_SLOW_RAMP":
            if j >= at:
                r["gas"] = min(2500, 400 + 4 * (j - at))
        elif fault == "PIR_FLOOD":
            if at <= j < at + 14:
                r["pir"] = (j - at) % 2
    return rows


def rnd_small(j):
    return (j * 37) % 50


EXPECT = {"TEMP_SPOOF": {"TEMP_JUMP"},
          "GAS_SPIKE_1200": {"GAS_SPIKE", "GAS_ALARM"},
          "GAS_ALARM_2400": {"GAS_ALARM", "GAS_SPIKE"},
          "GAS_SLOW_RAMP": {"GAS_ALARM", "GAS_SPIKE"},
          "PIR_FLOOD": {"PIR_FLOOD"}}
FIXED_ONLY = {"GAS_ALARM"}          # baseline = course/TP2 fixed threshold on gas


def run_detector(rows):
    p = Plausibility()
    out = []
    for r in rows:
        ev = []
        ev += p.check_pir(r["pir"], r["k"] * TICK)
        if r["k"] % 4 == 0:
            ev += p.check_temp(r["temp"])
            ev += p.check_gas(r["gas"])
        for name, _ in ev:
            out.append((r["k"], name))
    return out


def experiment_plausibility():
    rnd = random.Random(SEED + 1)
    runs = 100
    # false positives on clean traces
    fp = {"temp": 0, "gas": 0, "pir": 0}
    samples = 0
    for _ in range(runs):
        rows = normal_trace(rnd)
        samples += len(rows)
        for _, name in run_detector(rows):
            if name == "TEMP_JUMP":
                fp["temp"] += 1
            elif name in ("GAS_SPIKE", "GAS_ALARM"):
                fp["gas"] += 1
            elif name == "PIR_FLOOD":
                fp["pir"] += 1
    res = {"clean_ticks": samples, "false_alarms": fp, "faults": {}}
    for fault, expected in EXPECT.items():
        hit_full = hit_fixed = hit_adapt = 0
        win = 700 if fault == "GAS_SLOW_RAMP" else 120
        for _ in range(runs):
            rows = normal_trace(rnd)
            at = rnd.randint(300, 750)
            rows = inject(rows, fault, at)
            evs = [(k, n) for k, n in run_detector(rows) if at <= k <= at + win]
            hit_full += any(n in expected for _, n in evs)
            hit_fixed += any(n in FIXED_ONLY for _, n in evs)
            hit_adapt += any(n == "GAS_SPIKE" for _, n in evs)
        res["faults"][fault] = {"recall_full_pct": round(100.0 * hit_full / runs, 1),
                                "recall_fixed_threshold_pct": round(100.0 * hit_fixed / runs, 1),
                                "recall_adaptive_only_pct": round(100.0 * hit_adapt / runs, 1)}
    return res


# ------------------------------------------------------------------ E3: overhead
def experiment_overhead():
    rnd = random.Random(SEED + 2)
    d = tempfile.mkdtemp()
    log = ChainLog(os.path.join(d, "l"), os.path.join(d, "s"), K0)
    n = 150
    t0 = time.perf_counter()
    for i in range(n):
        log.append(1_000_000 + i, "GAS_ALARM", rnd.randint(0, 4000))
    t_app = (time.perf_counter() - t0) / n
    with open(log.path) as f:
        lines = f.read().splitlines()
    size = sum(len(x) + 1 for x in lines) / n
    t0 = time.perf_counter()
    for _ in range(20):
        verify_records(lines, K0)
    t_ver = (time.perf_counter() - t0) / 20
    return {"records": n, "bytes_per_record": round(size, 1),
            "host_append_ms": round(t_app * 1000, 3),
            "host_verify_full_ms": round(t_ver * 1000, 3),
            "note": "CPython on the build host: indicative only, NOT ESP32 timing"}


if __name__ == "__main__":
    out = {"seed": SEED, "trials_per_attack": TRIALS,
           "data_status": "synthetic, host-run (CPython); not measured on ESP32/Wokwi",
           "tamper": experiment_tamper(),
           "plausibility": experiment_plausibility(),
           "overhead": experiment_overhead()}
    with open(os.path.join(OUT, "results.json"), "w") as f:
        json.dump(out, f, indent=2)
    print(json.dumps(out, indent=2))
